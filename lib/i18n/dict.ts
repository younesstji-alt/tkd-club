export const dictionaries: Record<Lang, Dict> = { ar, fr };

export function translate(lang: Lang, key: DictKey, vars?: Record<string, string | number>): string {
  let s = dictionaries[lang][key] ?? dictionaries.ar[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

export type T = (key: DictKey, vars?: Record<string, string | number>) => string;
